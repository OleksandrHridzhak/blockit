import Foundation

let window = AccessWindow(requestID: "instagram", readyAt: 1_020, now: 1_000)
assert(window.startsAt == 1_020)
assert(window.monitorEndsAt - window.startsAt >= 15 * 60, "The short pause must not be used as the monitor interval")
assert(!window.canActivate(requestID: "instagram", now: 1_019.999), "Never open before the pause ends")
assert(window.canActivate(requestID: "instagram", now: 1_020), "Open at the deadline")
assert(window.canActivate(requestID: "instagram", now: 1_045), "A late iOS callback can still open the remaining session")
assert(!window.canActivate(requestID: nil, now: 1_020), "Cancellation must invalidate a pending callback")
assert(!window.canActivate(requestID: "other-app", now: 1_020), "A replaced request must not be opened by a stale callback")
assert(!window.canActivate(requestID: "instagram", now: window.endsAt), "An expired callback must not create fresh access")
let restored = try JSONDecoder().decode(AccessWindow.self, from: JSONEncoder().encode(window))
assert(restored.startsAt == window.startsAt && restored.endsAt == window.endsAt, "Process restarts must preserve the same deadline")
let fractional = AccessWindow(requestID: "fractional", readyAt: 1_020.75, now: 1_000.5)
assert(fractional.startsAt == 1_021, "The system callback must not be scheduled before a fractional deadline")
assert(fractional.canActivate(requestID: "fractional", now: 1_021))
let migrated = AccessWindow(requestID: "old-build", readyAt: 1_000, now: 1_300)
assert(migrated.monitorEndsAt - migrated.startsAt >= 15 * 60, "An overdue request must still produce a valid monitoring interval")
let midnight = AccessWindow(requestID: "midnight", readyAt: 86_410, now: 86_390)
assert(!midnight.canActivate(requestID: "midnight", now: 86_399))
assert(midnight.canActivate(requestID: "midnight", now: 86_410))
print("PASS: native access-window regression checks (deadline, cancellation, replacement, expiry, persistence, migration, midnight).")

let customSession = AccessWindow(requestID: "custom", readyAt: 1_020, now: 1_000, sessionMinutes: 37)
assert(customSession.endsAt - customSession.startsAt == 37 * 60)
assert(customSession.canActivate(requestID: "custom", now: customSession.endsAt - 1))
assert(!customSession.canActivate(requestID: "custom", now: customSession.endsAt))
let shortSession = AccessWindow(requestID: "short", readyAt: 1_020, now: 1_000, sessionMinutes: 1)
assert(shortSession.endsAt - shortSession.startsAt == 60)
assert(shortSession.expiryMonitorEndsAt - shortSession.endsAt >= 15 * 60)
assert(shortSession.monitorEndsAt - shortSession.startsAt >= 15 * 60)
assert(shortSession.expiryMonitorID == "short.expiry")
assert(shortSession.usageSeconds == 60)
assert(customSession.monitorEndsAt >= customSession.endsAt, "Usage monitoring must cover long sessions, not end after fifteen minutes")
let twoMinutes = AccessWindow(requestID: "two", readyAt: 1000, now: 1000, sessionMinutes: 2)
assert(twoMinutes.endsAt == 1120)
assert(!twoMinutes.canActivate(requestID: "two", now: 1120))
let customRestored = try JSONDecoder().decode(AccessWindow.self, from: JSONEncoder().encode(customSession))
assert(customRestored.endsAt == customSession.endsAt)
print("PASS: custom session duration, native minimum, expiry and persistence.")

assert(AccessWindow.pauseDeadline(mode: "countdown", seconds: 30, now: 1000) == 1030)
assert(AccessWindow.pauseDeadline(mode: "typing", seconds: 60, now: 1000) == 1000)
assert(AccessWindow.pauseDeadline(mode: "reflection", seconds: 60, now: 1000) == 1000)
print("PASS: task modes do not add an artificial countdown.")
assert(AccessWindow.microlearningDeadline(existing: 0, seconds: 20, now: 1000) == 1020)
assert(AccessWindow.microlearningDeadline(existing: 1020, seconds: 20, now: 1010) == 1020)
print("PASS: microlearning starts on entry and reopening preserves its deadline.")
assert(AccessWindow.isMicrolearning("microlearning"))
assert(AccessWindow.isMicrolearning("microlearning-v2"))
assert(!AccessWindow.isMicrolearning("countdown"))

var events: [PauseHistory.Event] = []
func log(_ outcome: String, request: String = "first", group: String = "social") {
  events = PauseHistory.recording(outcome, requestID: request, groupID: group,
    groupName: "Соцмережі", timestampMs: 1000, in: events)
}
log("intervened")
log("intervened")
assert(events.count == 1, "Repeated shield taps must not duplicate an attempt")
log("continued")
log("continued")
log("dismissed")
assert(events.count == 2, "Only one final decision per request, including delayed callbacks")
log("intervened", request: "second", group: "work")
log("dismissed", request: "second", group: "work")
log("continued", request: "second", group: "work")
assert(events.count == 4 && events[0].appId == "work")
assert(events.filter { $0.outcome == "continued" }.count == 1)
assert(events.filter { $0.outcome == "dismissed" }.count == 1)
let persistedEvents = try JSONDecoder().decode([PauseHistory.Event].self, from: JSONEncoder().encode(events))
assert(persistedEvents.count == 4 && persistedEvents[0].groupName == "Соцмережі")
log("unknown")
assert(events.count == 4)
for index in 0..<2100 { log("intervened", request: "history-\(index)") }
assert(events.count == 2000, "History is bounded across processes")
print("PASS: native history deduplication, terminal outcomes, group snapshots, persistence and retention.")
